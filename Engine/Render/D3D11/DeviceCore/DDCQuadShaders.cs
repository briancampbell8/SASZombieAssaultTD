        // ------------------------------------------------------------------------------------------------
        //  Shader Creation API
        // ------------------------------------------------------------------------------------------------

        public ID3D11VertexShader CreateVertexShader(ID3D11Device device)
        {
            return device.CreateVertexShader(QuadVS_Bytecode);
        }

        public ID3D11PixelShader CreatePixelShader(ID3D11Device device)
        {
            return device.CreatePixelShader(QuadPS_Bytecode);
        }

        public ID3D11InputLayout CreateInputLayout(ID3D11Device device)
        {
            var inputElements = new[]
            {
                new InputElementDescription("POSITION", 0, Format.R32G32_Float, 0, 0),
                new InputElementDescription("TEXCOORD", 0, Format.R32G32_Float, 8, 0),
                new InputElementDescription("COLOR",    0, Format.R32G32B32A32_Float, 16, 0)
            };

            return device.CreateInputLayout(inputElements, QuadVS_Bytecode);
        }
    }
